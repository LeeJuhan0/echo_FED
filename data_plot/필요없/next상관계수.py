fig, axes = plt.subplots(2, 3, figsize=(15, 8))
axes = axes.flatten()

def add_panel(ax, df, xcol, ycol):
    x = df[xcol].values
    y = df[ycol].values
    r,p = stats.pearsonr(x,y)
    m,b = np.polyfit(x,y,1)
    xs = np.linspace(x.min(), x.max(), 150)
    ax.scatter(x,y, color='#2c7fb8', alpha=0.85, edgecolors='white', linewidth=0.5)
    ax.plot(xs, m*xs+b, color='firebrick', lw=1.2)
    ax.set_xlabel(xcol); ax.set_ylabel(ycol)
    ax.set_title(f"{xcol} vs {ycol}")
    ax.text(0.02,0.95,f"r={r:.3f}\np={p:.1e}", transform=ax.transAxes,
            va='top', ha='left', fontsize=9,
            bbox=dict(boxstyle='round,pad=0.25', fc='white', ec='gray', alpha=0.7))
    ax.grid(alpha=0.3)

for ax,(xcol,ycol) in zip(axes,pairs):
    add_panel(ax, panel_df, xcol, ycol)

plt.suptitle("Scatter (Method B: 2020-03x,y 유지)", fontsize=14, y=0.98)
